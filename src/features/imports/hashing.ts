/**
 * SHA-256 and UUIDs that also work outside a "secure context".
 *
 * Browsers expose crypto.subtle and crypto.randomUUID() only on HTTPS and
 * localhost. Opening the dev server at a LAN/link-local address (http://<ip>)
 * removes both, which made file selection fail. crypto.getRandomValues() is
 * available everywhere, so it backs the UUID fallback; SHA-256 falls back to the
 * small implementation below (only used when crypto.subtle is missing).
 */

export function randomId(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40; // version 4
  b[8] = (b[8] & 0x3f) | 0x80; // RFC 4122 variant
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

export async function sha256Hex(data: ArrayBuffer | Uint8Array): Promise<string> {
  const bytes = data instanceof Uint8Array ? data : new Uint8Array(data);
  if (globalThis.crypto?.subtle) {
    const digest = await crypto.subtle.digest("SHA-256", bytes as Uint8Array<ArrayBuffer>);
    return toHex(new Uint8Array(digest));
  }
  return toHex(sha256(bytes));
}

const toHex = (bytes: Uint8Array) =>
  Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");

